#!/usr/bin/env python3
"""Build static GitHub Pages files from templates, JSON, and Markdown."""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import html
import json
from pathlib import Path
import re
from string import Template
import xml.etree.ElementTree as ET
from zoneinfo import ZoneInfo

from markdown_it import MarkdownIt
import yaml

ROOT = Path(__file__).resolve().parents[1]
SITE = "https://taewan2002.github.io"
MARKER = "<!-- Generated by scripts/build.py; edit templates/ or content/. -->\n"
NAV = [("about", "/"), ("research", "/research/"), ("company", "/company/"), ("project", "/project/"), ("blog", "/blog/")]
LANGUAGES = ("en", "ko")


def prefix(lang):
    return "/ko" if lang == "ko" else ""


def local_url(path, lang):
    return prefix(lang) + path


def esc(value):
    return html.escape(str(value), quote=True)


def read_json(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def template(name, **values):
    return Template((ROOT / "templates" / name).read_text(encoding="utf-8")).substitute(values)


def load_posts(include_drafts=False):
    today = dt.datetime.now(ZoneInfo("Asia/Seoul")).date()
    renderer = MarkdownIt("commonmark", {"html": False}).enable("table").enable("strikethrough")
    default_image = renderer.renderer.rules["image"]

    def responsive_image(tokens, idx, options, env):
        """Use an authored mobile companion for local blog SVGs, when present."""
        rendered = default_image(tokens, idx, options, env)
        src = tokens[idx].attrGet("src") or ""
        if re.fullmatch(r"/assets/blog/[a-z0-9/-]+\.svg", src):
            mobile = src.removesuffix(".svg") + "-mobile.svg"
            if (ROOT / mobile.lstrip("/")).is_file():
                return f'<picture class="article-diagram"><source media="(max-width: 600px)" srcset="{esc(mobile)}">{rendered}</picture>'
        return rendered

    renderer.renderer.rules["image"] = responsive_image

    def table_open(tokens, idx, options, env):
        label = ("표 — 가로로 스크롤할 수 있습니다" if env["lang"] == "ko"
                 else "Table — scroll horizontally to see all columns")
        return f'<div class="table-scroll" role="region" tabindex="0" aria-label="{label}"><table>\n'

    renderer.renderer.rules["table_open"] = table_open
    renderer.renderer.rules["table_close"] = lambda tokens, idx, options, env: "</table></div>\n"

    def read_post(source):
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", source.stem):
            raise ValueError(f"{source.name}: use a lowercase hyphenated filename")
        raw = source.read_text(encoding="utf-8")
        match = re.match(r"\A---\r?\n(.*?)\r?\n---\r?\n(.*)\Z", raw, re.S)
        if not match:
            raise ValueError(f"{source.name}: missing YAML front matter")
        meta = yaml.safe_load(match.group(1))
        if not isinstance(meta, dict):
            raise ValueError(f"{source.name}: front matter must be a mapping")
        for field in ("title", "summary"):
            if not isinstance(meta.get(field), str) or not meta[field].strip():
                raise ValueError(f"{source.name}: {field} must be a nonempty string")
        date = dt.date.fromisoformat(str(meta.get("date")))
        lang = meta.get("lang", "ko")
        if lang not in ("ko", "en"):
            raise ValueError(f"{source.name}: lang must be ko or en")
        draft = meta.get("draft", True)
        if not isinstance(draft, bool):
            raise ValueError(f"{source.name}: draft must be true or false")
        hidden = draft or date > today
        return {"slug": source.stem, "title": meta["title"], "summary": meta["summary"],
                      "lang": lang, "date": date.isoformat(), "display_date": date.strftime("%Y.%m.%d"),
                      "draft": hidden, "source_draft": draft,
                      "body": renderer.render(match.group(2), {"lang": lang}), "url": f"/blog/{source.stem}/"}

    post_root = ROOT / "content/posts"
    originals = {source.stem: read_post(source) for source in sorted(post_root.glob("*.md"))
                 if not source.stem.startswith("_")}
    for post in originals.values():
        post["editions"] = {post["lang"]: dict(post)}
    for lang in LANGUAGES:
        for source in sorted((post_root / lang).glob("*.md")):
            if source.stem.startswith("_"):
                continue
            if source.stem not in originals:
                raise ValueError(f"{source}: translation needs an original post with the same filename")
            post = originals[source.stem]
            edition = read_post(source)
            if edition["lang"] != lang or lang in post["editions"]:
                raise ValueError(f"{source}: translation language must match its folder and differ from the original")
            if (edition["date"], edition["source_draft"]) != (post["date"], post["source_draft"]):
                raise ValueError(f"{source}: translation date and draft state must match the original")
            post["editions"][lang] = edition
    posts = [post for post in originals.values() if include_drafts or not post["draft"]]
    return sorted(posts, key=lambda p: (p["date"], p["slug"]), reverse=True)


def paper_html(paper, lang, copy):
    p = {k: esc(v) for k, v in paper.items() if k not in ("links", "authors")}
    heading = f'<a href="{p["url"]}">{p["title"]}</a>' if p["url"] else p["title"]
    summary = p["summary_ko"] if lang == "ko" else p["summary"]
    venue = copy["preprint"] if paper["venue"] == "Preprint" else p["venue"]
    figure_label = esc(copy["view_figure"].format(name=paper["id"]))
    links = "".join(f'<a href="{esc(a["url"])}">{esc(copy.get("link_" + a["label"].lower(), a["label"]))}</a>' for a in paper["links"])
    return f'''<article class="paper" id="{p['id']}" data-publication-date="{p['date']}">
    <figure class="paper-figure"><a href="/{p['image']}" target="_blank" rel="noopener" aria-label="{figure_label}"><img src="/{p['image']}" alt="{p['image_alt_ko'] if lang == 'ko' else p['image_alt']}" width="{p['image_width']}" height="{p['image_height']}" loading="lazy"></a></figure>
    <div class="paper-content"><p class="venue"><span>{venue}</span><time datetime="{p['date']}" title="{p['date_note']}">{p['date'].replace('-', '.')}.</time></p>
    <h3 lang="en">{heading}</h3><p class="authors" lang="en">{paper['authors']}</p><p class="paper-summary">{summary}</p><div class="paper-links">{links}</div></div></article>'''


def selected_html(paper, lang):
    p = {k: esc(v) for k, v in paper.items() if k not in ("links", "authors")}
    venue = re.search(r"\(([^)]+)\)", paper["venue"])
    short_venue = esc(venue.group(1) if venue else paper["venue"])
    name = p["title"].split(":", 1)[0]
    summary = p["summary_ko"] if lang == "ko" else p["summary"]
    url = local_url(f"/research/#{p['id']}", lang)
    return f'''<article class="selected-paper" id="{p['id']}"><a class="thumbnail" href="{url}" aria-label="{name}"><img src="/{p['image']}" alt="{p['image_alt_ko'] if lang == 'ko' else p['image_alt']}" width="{p['image_width']}" height="{p['image_height']}" loading="lazy"></a><div><p class="small-label">{short_venue} · {p['date'][:4]}</p><h3><a href="{url}">{name}</a></h3><p>{summary}</p></div></article>'''


def post_list(posts, lang, copy, home=False):
    if not posts:
        return f'<p class="blog-empty">{copy["empty_title"]}</p>'
    heading = "h3" if home else "h2"
    rows = []
    for p in posts:
        p = p["editions"].get(lang, p)
        label = copy["draft_label"] if p["draft"] else ""
        rows.append(f'<li class="post-item"><a href="{local_url(p["url"], lang)}"><time datetime="{p["date"]}">{p["display_date"]}</time><{heading}><span>{label}</span><span lang="{p["lang"]}">{esc(p["title"])}</span></{heading}><span class="post-arrow" aria-hidden="true">↗</span></a></li>')
    return '<ul class="post-list">' + "".join(rows) + '</ul>'


def project_summary_html(project, lang):
    suffix = "" if lang == "ko" else "_en"
    return template("project-summary.html", **{
        "project_" + field: esc(project[field + suffix])
        for field in ("summary", "description", "detail")
    })


def project_html(project, lang, copy):
    p = {k: esc(v) for k, v in project.items()}
    paper = f'<a href="{p["paper"]}">{copy["link_paper"]} ↗</a>' if "paper" in p else ""
    kind = p["kind_ko"] if lang == "ko" else p["kind"]
    github_label = esc(copy["project_github"].format(name=project["name"]))
    return f'''<article class="home-section source-project" id="{p['id']}" aria-labelledby="{p['id']}-title">
    <div class="section-label"><h2 id="{p['id']}-title">{p['name']}</h2><span class="small-label">{kind}</span><a class="text-link" href="{p['url']}">{copy['view_github']} <span aria-hidden="true">↗</span></a>{paper}</div>
    <div class="section-content"><a class="featured-art" href="{p['url']}" aria-label="{github_label}"><img src="/{p['image']}" alt="{p['image_alt_ko'] if lang == 'ko' else p['image_alt']}" width="{p['image_width']}" height="{p['image_height']}" loading="lazy"></a>{project_summary_html(project, lang)}</div></article>'''


def company_html(company, lang, common):
    copy = {k: esc(v) for k, v in company["copy"][lang].items() if isinstance(v, str)}
    capabilities = "".join(
        f'<article class="company-capability"><span class="item-number" aria-hidden="true">{index:02}</span><h3>{esc(item[lang]["title"])}</h3><p>{esc(item[lang]["body"])}</p></article>'
        for index, item in enumerate(company["capabilities"], 1))
    products = "".join(
        f'<article class="company-product"><div class="company-product-heading"><img src="/{esc(item["image"])}" alt="" width="56" height="56" loading="lazy"><div><p class="small-label">{esc(item[lang]["category"])}</p><h3>{esc(item["name"])}</h3></div></div><p>{esc(item[lang]["body"])}</p><a class="text-link" href="{esc(item["url"])}">{copy["product_link"]} ↗</a></article>'
        for item in company["products"])
    cases = "".join(
        f'<article class="company-case"><div><p class="small-label">{esc(item[lang]["category"])}</p><h3>{esc(item[lang]["title"])}</h3><p class="company-case-context">{esc(item[lang]["context"])}</p></div><div><p>{esc(item[lang]["body"])}</p><a class="text-link" href="{esc(item["url"])}">{copy["case_link"]} ↗</a></div></article>'
        for item in company["cases"])
    steps = "".join(f'<li><span aria-hidden="true">{index:02}</span>{esc(step)}</li>'
                    for index, step in enumerate(company["copy"][lang]["steps"], 1))
    edge_flow = "".join(f'<li><span class="item-number" aria-hidden="true">{index:02}</span><h3>{esc(step["title"])}</h3><p>{esc(step["body"])}</p></li>'
                        for index, step in enumerate(company["copy"][lang]["edge_steps"], 1))
    return template("company.html", **common, **copy, capability_items=capabilities,
                    product_items=products, case_items=cases, approach_steps=steps, edge_flow=edge_flow)


def build(include_drafts=False):
    profile = read_json("content/profile.json")
    papers = read_json("content/publications.json")
    projects = read_json("content/projects.json")
    featured_project = next(p for p in projects if p["id"] == "human-researcher")
    company = read_json("content/company.json")
    posts = load_posts(include_drafts)
    profile_links = {k: esc(profile[k]) for k in ("email", "company_email", "scholar", "github", "linkedin")}
    names = {"en": profile["name"], "ko": profile["korean_name"]}
    translations = read_json("content/site-copy.json")
    if translations["en"].keys() != translations["ko"].keys():
        raise ValueError("English and Korean UI copy must have matching keys")
    by_id = {p["id"]: p for p in papers}
    outputs = {}
    stylesheet_version = hashlib.sha256((ROOT / "styles.css").read_bytes()).hexdigest()[:12]

    def page(path, section, title, description, content, lang, draft=False, article=False,
             article_languages=(), content_lang=None):
        copy = translations[lang]
        nav = "".join(f'<a href="{local_url(url, lang)}" lang="en"' + (' aria-current="page"' if label == section else '') + f'>{translations["en"]["nav_" + label]}</a>' for label, url in NAV)
        url = "/" + path.removesuffix("index.html")
        language_links = []
        for option, label, accessible_label in (("en", "EN", "English"), ("ko", "KO", "한국어")):
            if option == lang:
                language_links.append(f'<span lang="{option}" aria-label="{accessible_label}" aria-current="true">{label}</span>')
            else:
                language_links.append(f'<a data-language-switch href="{local_url(url, option)}" lang="{option}" aria-label="{accessible_label}">{label}</a>')
        available_languages = article_languages if article else LANGUAGES
        alternates = "\n".join(f'<link rel="alternate" hreflang="{option}" href="{SITE + local_url(url, option)}">' for option in available_languages)
        default_lang = "en" if "en" in available_languages else content_lang
        alternates += f'\n<link rel="alternate" hreflang="x-default" href="{SITE + local_url(url, default_lang)}">'
        output_path = (prefix(lang) + "/" + path).lstrip("/")
        outputs[output_path] = MARKER + template("base.html", **copy, section=section, lang=lang, display_name=esc(names[lang]), title=esc(title), description=esc(description),
            og_type="article" if article else "website", canonical=SITE + local_url(url, content_lang if article else lang),
            navigation=nav, content=content, home_url=local_url("/", lang), language_switch='<span class="language-divider" aria-hidden="true">/</span>'.join(language_links),
            alternate_links=alternates, github=profile_links["github"], linkedin=profile_links["linkedin"], stylesheet_version=stylesheet_version,
            extra_head='<meta name="robots" content="noindex, nofollow">' if draft else "")

    for lang in LANGUAGES:
        copy = translations[lang]
        common = {**copy, **profile_links, "prefix": prefix(lang), "display_name": esc(names[lang])}
        interests = profile["interests_ko"] if lang == "ko" else profile["interests"]
        home = template("home.html", **common,
            featured_project_summary=project_summary_html(featured_project, lang),
            home_interests="".join(f'<li>{esc(k)}</li>' for k in interests),
            selected_papers="".join(selected_html(by_id[k], lang) for k in profile["selected_papers"]),
            recent_posts=post_list(posts[:3], lang, copy, home=True))
        home += '<script src="/assets/legacy-links.js" defer></script>'
        page("index.html", "about", copy["home_title"], copy["home_description"], home, lang)
        bio = profile["bio_ko"] if lang == "ko" else profile["bio"]
        research = template("research.html", **common, bio=bio,
            interests="".join(f'<li>{esc(k)}</li>' for k in interests), paper_count=len(papers),
            papers="".join(paper_html(p, lang, copy) for p in papers), patents=template("patents.html", **copy))
        page("research/index.html", "research", copy["nav_research"] + " — " + names[lang], copy["research_description"], research, lang)
        page("company/index.html", "company", copy["nav_company"] + " — " + names[lang], copy["company_summary"],
            company_html(company, lang, common), lang)
        page("project/index.html", "project", copy["nav_project"] + " — " + names[lang], copy["source_description"],
            template("project.html", **common, projects="".join(project_html(p, lang, copy) for p in projects)), lang)
        # Keep previously shared local preview links working, including anchors.
        outputs[(prefix(lang) + "/open-source/index.html").lstrip("/")] = MARKER + template("redirect.html",
            lang=lang, destination=local_url("/project/", lang), label=copy["nav_project"], canonical=SITE + local_url("/project/", lang))
        page("blog/index.html", "blog", copy["nav_blog"] + " — " + names[lang], copy["blog_lead"],
            template("blog.html", **common, posts=post_list(posts, lang, copy)), lang)
        for p in posts:
            edition = p["editions"].get(lang, p)
            notice = f'<p class="draft-notice">{copy["draft_notice"]}</p>' if p["draft"] else ""
            body = template("post.html", **common, post_title=esc(edition["title"]), summary=esc(edition["summary"]),
                date=p["date"], display_date=p["display_date"],
                post_lang=edition["lang"], body=edition["body"], draft_banner=notice)
            page(f'blog/{p["slug"]}/index.html', "blog", edition["title"] + " — " + names[lang], edition["summary"], body, lang,
                 draft=p["draft"], article=True, article_languages=tuple(p["editions"]), content_lang=edition["lang"])

    moved_ids = [p["id"] for p in papers if p["id"] not in profile["selected_papers"]] + ["patents"]
    outputs["assets/legacy-links.js"] = '// Generated by scripts/build.py\n' + f'if ({json.dumps(moved_ids)}.includes(location.hash.slice(1))) location.replace((location.pathname.startsWith("/ko/") ? "/ko" : "") + "/research/" + location.hash);\n'

    rss = ET.Element("rss", version="2.0")
    channel = ET.SubElement(rss, "channel")
    for key, value in [("title", "Taewan Cho — Blog"), ("link", SITE + "/blog/"), ("description", "연구, 만드는 일, 그리고 일상에서 떠오른 생각들.")]:
        ET.SubElement(channel, key).text = value
    for p in posts:
        if p["draft"]:
            continue
        item = ET.SubElement(channel, "item")
        for key, value in [("title", p["title"]), ("link", SITE + local_url(p["url"], p["lang"])), ("guid", SITE + p["url"]), ("description", p["summary"]), ("pubDate", dt.date.fromisoformat(p["date"]).strftime("%a, %d %b %Y 00:00:00 +0900"))]:
            ET.SubElement(item, key).text = value
    outputs["feed.xml"] = '<?xml version="1.0" encoding="utf-8"?>\n' + ET.tostring(rss, encoding="unicode") + "\n"
    for name, contents in outputs.items():
        path = ROOT / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents, encoding="utf-8")
    # Only remove obsolete article pages generated by this script.
    for lang in LANGUAGES:
        for old in (ROOT / prefix(lang).lstrip("/") / "blog").glob("*/index.html"):
            if str(old.relative_to(ROOT)) not in outputs and old.read_text().startswith(MARKER):
                old.unlink()
                if not any(old.parent.iterdir()):
                    old.parent.rmdir()
    print(f"Built {len(outputs)} static files; {len(papers)} papers, {len(projects)} projects, {len(posts)} posts.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--drafts", action="store_true", help="Include drafts and future posts in local preview (never RSS).")
    build(parser.parse_args().drafts)
